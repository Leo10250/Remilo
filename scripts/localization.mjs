import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import ts from 'typescript';

const root = path.resolve(import.meta.dirname, '..');
const xml = s => s.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll("'", "\\'").replaceAll('"', '\\"');
export function parseCatalog(text) {
  const value = JSON.parse(text);
  const tree = ts.parseJsonText('catalog.json', text);
  const visit = node => {
    if (ts.isObjectLiteralExpression(node)) {
      const keys = new Set();
      for (const property of node.properties) {
        const key = property.name?.text;
        if (keys.has(key)) throw new Error('Duplicate catalog property: ' + key);
        keys.add(key);
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(tree);
  return value;
}
export function generate(catalog) {
  const messages = catalog.messages;
  if (!messages || !Object.keys(messages).length) throw new Error('Empty localization catalog');
  const names = new Set(), en = {}, zh = {}, args = {};
  for (const [key, entry] of Object.entries(messages)) {
    if (!/^[a-z][a-z0-9_]*$/.test(key) || names.has(key)) throw new Error('Invalid/duplicate message key: ' + key);
    names.add(key);
    if (entry.en != null && entry['zh-Hans'] != null && (typeof entry.en === 'string') !== (typeof entry['zh-Hans'] === 'string')) throw new Error('Mismatched native plural resource: ' + key);
    for (const [name, type] of Object.entries(entry.args ?? {})) if (!/^[a-zA-Z][a-zA-Z0-9]*$/.test(name) || !['string', 'number', 'string | number'].includes(type)) throw new Error('Invalid argument: ' + key + '.' + name);
    for (const language of ['en', 'zh-Hans']) {
      const value = entry[language];
      const variants = typeof value === 'string' ? { other: value } : value;
      if (!variants?.other || (typeof value !== 'string' && language === 'en' && !variants.one)) throw new Error('Missing translation/plural: ' + key);
      for (const text of Object.values(variants)) {
        if (typeof text !== 'string' || !text.trim()) throw new Error('Empty translation: ' + key);
        const found = [...new Set([...text.matchAll(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g)].map(x => x[1]))].sort();
        if (JSON.stringify(found) !== JSON.stringify(Object.keys(entry.args ?? {}).sort())) throw new Error('Placeholder mismatch: ' + key + ' ' + language);
      }
    }
    en[key] = entry.en; zh[key] = entry['zh-Hans']; args[key] = entry.args ?? {};
  }
  const ts = `// Generated by scripts/localization.mjs. Edit localization/catalog.json.\nexport const catalogs = ${JSON.stringify({ en, 'zh-Hans': zh }, null, 2)} as const;\nexport type MessageKey = keyof typeof catalogs.en;\nexport interface MessageArguments {\n${Object.entries(args).map(([k,v]) => `  ${k}: ${Object.keys(v).length ? '{ '+Object.entries(v).map(([n,t])=>`${n}: ${t}`).join('; ')+' }' : 'Record<string, never>'};`).join('\n')}\n}\n`;
  const base = 'modules/remilo-alarm/android/src/main/';
  const resources = language => `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/localization.mjs. -->\n<resources>\n${Object.entries(messages).map(([key,entry]) => {
    const value=entry[language], positional=text=>xml((Object.keys(entry.args??{}).length ? text.replaceAll('%','%%') : text).replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g,(_,n)=>`%${Object.keys(entry.args??{}).indexOf(n)+1}$s`));
    return typeof value==='string'?`  <string name="l10n_${key}">${positional(value)}</string>`:`  <plurals name="l10n_${key}">\n${Object.entries(value).map(([q,t])=>`    <item quantity="${q}">${positional(t)}</item>`).join('\n')}\n  </plurals>`;
  }).join('\n')}\n</resources>\n`;
  // Keep generated JVM methods below the bytecode limit, independently of catalog size.
  const rows = Object.entries(messages).map(([k,v])=>`    "${k}" to Entry(R.${typeof v.en==='string'?'string':'plurals'}.l10n_${k}, ${typeof v.en!=='string'}, listOf(${Object.keys(v.args??{}).map(n=>`"${n}"`).join(', ')}), ${JSON.stringify(typeof v.en==='string'?v.en:v.en.other).replaceAll('$','\\$')}, ${!!v.calendarStatus})`);
  const chunks = Array.from({length:Math.ceil(rows.length/80)},(_,i)=>rows.slice(i*80,(i+1)*80));
  const kotlin=`// Generated by scripts/localization.mjs.\npackage com.remilo.alarm.presentation\n\nimport com.remilo.alarm.R\n\nobject MessageCatalog {\n  data class Entry(val resource: Int, val plural: Boolean, val args: List<String>, val english: String, val calendarStatus: Boolean)\n  val entries: Map<String, Entry> by lazy { buildMap { ${chunks.map((_,i)=>`putAll(chunk${i}());`).join(' ')} } }\n${chunks.map((rows,i)=>`  private fun chunk${i}(): Map<String, Entry> = mapOf(\n${rows.join(',\n')}\n  )`).join('\n')}\n}\n`;
  const accessors = `// Generated by scripts/localization.mjs. Edit localization/catalog.json.\npackage com.remilo.alarm.presentation\n\n/** Typed descriptors for native presentation and persisted status writes. */\nobject NativeMessages {\n${Object.entries(args).map(([key, fields]) => `  fun ${key}(${Object.entries(fields).map(([name,type])=>`${name}: ${type==='number'?'Number':type==='string'?'String':'Any'}`).join(', ')}): L10n.Message = L10n.Message("${key}"${Object.keys(fields).length ? ', mapOf('+Object.keys(fields).map(name=>`"${name}" to ${name}.toString()`).join(', ')+')' : ''})`).join('\n')}\n}\n`;
  return new Map([['src/localization/catalog.generated.ts',ts],[base+'res/values/localization.xml',resources('en')],[base+'res/values-b+zh+Hans/localization.xml',resources('zh-Hans')],[base+'java/com/remilo/alarm/presentation/MessageCatalog.kt',kotlin],[base+'java/com/remilo/alarm/presentation/NativeMessages.kt',accessors]]);
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const catalog = parseCatalog(fs.readFileSync(path.join(root,'localization/catalog.json'),'utf8'));
  for(const [file,value] of generate(catalog)) {
    const destination=path.join(root,file);
    if(process.argv.includes('--check')) { if(!fs.existsSync(destination)||fs.readFileSync(destination,'utf8').replaceAll('\r\n','\n')!==value)throw new Error('Stale localization output: '+file); }
    else { fs.mkdirSync(path.dirname(destination),{recursive:true});fs.writeFileSync(destination,value); }
  }
  console.log(`${Object.keys(catalog.messages).length} English/Chinese messages ${process.argv.includes('--check')?'verified':'generated'}.`);
}
